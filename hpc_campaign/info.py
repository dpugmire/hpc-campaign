@dataclass(frozen=True)
class StepMappingInfo:
    """Compact mapping from output chunk indices to one activity input."""

    output_variable_id: int
    output_start: int
    count: int
    encoding: str
    source_start: int | None
    stride: int | None
    explicit_steps: tuple[int, ...] = ()

    def source_step(self, output_index: int) -> int:
        """Return the source step for one output index without expanding the mapping."""
        offset = output_index - self.output_start
        if offset < 0 or offset >= self.count:
            raise IndexError(f"Output index {output_index} is outside this mapping")
        if self.encoding == "explicit":
            return self.explicit_steps[offset]
        if self.source_start is None or self.stride is None:
            raise ValueError(f"Invalid {self.encoding} source-step mapping")
        return int(self.source_start) + offset * int(self.stride)


