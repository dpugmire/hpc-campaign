def _info_json_value(value: str | None) -> Any:
    if value is None:
        return None
    try:
        return json.loads(value)
    except (json.JSONDecodeError, TypeError):
        return None


def info_variables(  # pylint: disable=too-many-locals,too-many-statements
    info_data: InfoResult,
    cur: sqlite3.Cursor,
) -> None:
    """Load data-product entities and the activity graph into an InfoResult."""
    required_tables = {
        "campaign_run",
        "variable_definition",
        "logical_variable",
        "primary_variable",
        "activity_category",
        "activity_kind",
        "action_spec",
        "activity",
        "activity_input",
        "activity_output",
        "variable_chunk",
        "activity_input_step_mapping",
    }
    placeholders = ", ".join("?" for _name in required_tables)
    rows = sql_execute(
        cur,
        f"select name from sqlite_master where type = 'table' and name in ({placeholders})",
        tuple(required_tables),
    ).fetchall()
    if {str(row[0]) for row in rows} != required_tables:
        return

    for row in sql_execute(cur, "select runid, uuid, name from campaign_run order by runid"):
        run = RunInfo(id=int(row["runid"]), uuid=str(row["uuid"]), name=str(row["name"]))
        info_data.runs[run.id] = run

    variable_rows = sql_execute(
        cur,
        "select lv.variableid, lv.uuid, lv.runid, run.name as run_name, "
        "lv.definitionid, definition.name as definition_name, "
        "lv.datasetid, d.name as dataset_name, lv.name, "
        "primary_value.variableid is not null as is_primary, "
        "preview.name as preview_name, preview_run.name as preview_run_name, "
        "preview_dataset.name as preview_dataset_name "
        "from logical_variable as lv "
        "join campaign_run as run on run.runid = lv.runid "
        "join variable_definition as definition on definition.definitionid = lv.definitionid "
        "join dataset as d on d.rowid = lv.datasetid and d.deltime = 0 "
        "left join primary_variable as primary_value on primary_value.variableid = lv.variableid "
        "left join logical_variable as preview on preview.variableid = lv.preferred_preview_id "
        "left join campaign_run as preview_run on preview_run.runid = preview.runid "
        "left join dataset as preview_dataset on preview_dataset.rowid = preview.datasetid "
        "order by lv.variableid",
    )
    for row in variable_rows:
        preview = None
        if row["preview_name"] is not None:
            preview = VariableRef(
                str(row["preview_run_name"]),
                str(row["preview_dataset_name"]),
                str(row["preview_name"]),
            )
        variable_id = int(row["variableid"])
        loaded_variable = LogicalVariableInfo(
            id=variable_id,
            uuid=str(row["uuid"]),
            run_id=int(row["runid"]),
            run=str(row["run_name"]),
            definition_id=int(row["definitionid"]),
            definition=str(row["definition_name"]),
            dataset_id=int(row["datasetid"]),
            dataset=str(row["dataset_name"]),
            variable=str(row["name"]),
            primary=bool(row["is_primary"]),
            preferred_preview=preview,
        )
        info_data.variables[variable_id] = loaded_variable
        info_data._variable_index[loaded_variable.reference] = variable_id  # pylint: disable=protected-access

    activity_rows = sql_execute(
        cur,
        "select activity.activityid, activity.uuid, activity.runid, run.name as run_name, "
        "category.name as category, kind.name as action, spec.metadata as action_spec "
        "from activity join activity_kind as kind on kind.kindid = activity.kindid "
        "join activity_category as category on category.categoryid = kind.categoryid "
        "left join campaign_run as run on run.runid = activity.runid "
        "left join action_spec as spec on spec.specid = activity.specid "
        "order by activity.activityid",
    )
    for row in activity_rows:
        activity_id = int(row["activityid"])
        loaded_activity = ActivityInfo(
            id=activity_id,
            uuid=str(row["uuid"]),
            run_id=int(row["runid"]) if row["runid"] is not None else None,
            run=str(row["run_name"]) if row["run_name"] is not None else None,
            category=str(row["category"]),
            action=str(row["action"]),
            action_spec=_info_json_value(row["action_spec"]),
        )
        info_data.activities[activity_id] = loaded_activity
        info_data._activity_index[loaded_activity.uuid] = activity_id  # pylint: disable=protected-access

    inputs_by_id: dict[int, ActivityInputInfo] = {}
    input_rows = sql_execute(
        cur,
        "select input.inputid, input.activityid, input.variableid, input.role, "
        "run.name as run_name, dataset.name as dataset_name, variable.name as variable_name "
        "from activity_input as input "
        "join logical_variable as variable on variable.variableid = input.variableid "
        "join campaign_run as run on run.runid = variable.runid "
        "join dataset on dataset.rowid = variable.datasetid "
        "order by input.activityid, input.inputid",
    )
    for row in input_rows:
        input_activity = info_data.activities.get(int(row["activityid"]))
        input_variable = info_data.variables.get(int(row["variableid"]))
        if input_activity is None or input_variable is None:
            continue
        activity_input = ActivityInputInfo(
            id=int(row["inputid"]),
            role=str(row["role"]),
            variable_id=input_variable.id,
            reference=VariableRef(
                str(row["run_name"]),
                str(row["dataset_name"]),
                str(row["variable_name"]),
            ),
        )
        input_activity.inputs.append(activity_input)
        inputs_by_id[activity_input.id] = activity_input
        if input_activity.reference not in input_variable.used_by:
            input_variable.used_by.append(input_activity.reference)

    output_rows = sql_execute(
        cur,
        "select output.outputid, output.activityid, output.variableid, output.role, "
        "run.name as run_name, dataset.name as dataset_name, variable.name as variable_name "
        "from activity_output as output "
        "join logical_variable as variable on variable.variableid = output.variableid "
        "join campaign_run as run on run.runid = variable.runid "
        "join dataset on dataset.rowid = variable.datasetid "
        "order by output.activityid, output.outputid",
    )
    for row in output_rows:
        output_activity = info_data.activities.get(int(row["activityid"]))
        output_variable = info_data.variables.get(int(row["variableid"]))
        if output_activity is None or output_variable is None:
            continue
        activity_output = ActivityOutputInfo(
            id=int(row["outputid"]),
            role=str(row["role"]),
            variable_id=output_variable.id,
            reference=VariableRef(
                str(row["run_name"]),
                str(row["dataset_name"]),
                str(row["variable_name"]),
            ),
        )
        output_activity.outputs.append(activity_output)
        output_variable.generated_by = output_activity.reference

    chunk_rows = sql_execute(
        cur,
        "select chunk.chunkid, chunk.variableid, chunk.chunk_index, chunk.payload_datasetid, "
        "payload.name as payload_name, payload.uuid as payload_uuid, payload.fileformat as payload_fileformat "
        "from variable_chunk as chunk "
        "join dataset as payload on payload.rowid = chunk.payload_datasetid and payload.deltime = 0 "
        "order by chunk.variableid, chunk.chunk_index",
    )
    for row in chunk_rows:
        chunk_variable = info_data.variables.get(int(row["variableid"]))
        if chunk_variable is None:
            continue
        chunk = VariableChunkInfo(
            id=int(row["chunkid"]),
            chunk_index=int(row["chunk_index"]),
            payload_dataset_id=int(row["payload_datasetid"]),
            payload_dataset_name=str(row["payload_name"]),
            payload_dataset_uuid=str(row["payload_uuid"]),
            payload_file_format=str(row["payload_fileformat"]),
        )
        chunk_variable.chunks.append(chunk)

    mapping_rows = sql_execute(
        cur,
        "select inputid, output_variableid, output_start, count, encoding, "
        "source_start, stride, explicit_steps from activity_input_step_mapping "
        "order by inputid, output_variableid, output_start",
    )
    for row in mapping_rows:
        mapped_input = inputs_by_id.get(int(row["inputid"]))
        if mapped_input is None:
            continue
        raw_explicit = _info_json_value(row["explicit_steps"])
        explicit = tuple(int(step) for step in raw_explicit) if isinstance(raw_explicit, list) else ()
        mapped_input.step_mappings.append(
            StepMappingInfo(
                output_variable_id=int(row["output_variableid"]),
                output_start=int(row["output_start"]),
                count=int(row["count"]),
                encoding=str(row["encoding"]),
                source_start=(int(row["source_start"]) if row["source_start"] is not None else None),
                stride=int(row["stride"]) if row["stride"] is not None else None,
                explicit_steps=explicit,
            )
        )


def collect_info(  # pylint: disable=too-many-locals,too-many-statements
    args: argparse.Namespace, con: sqlite3.Connection
) -> InfoResult:
    cur = con.cursor()
    res = sql_execute(cur, "select id, name, version, modtime from info")
    row = res.fetchone()
    info_datasets = InfoResult(
        archive=ArchiveInfo(
            id=row[0],
            name=row[1],
            version=row[2],
            mod_time=row[3],
        )
    )

    #
    # Hosts and directories
    #
    delete_condition_where = " where deltime = 0"
    delete_condition_and = " and deltime = 0"
    if args.show_deleted:
        delete_condition_where = ""
        delete_condition_and = ""
    res = sql_execute(
        cur,
        "select rowid, hostname, longhostname from host" + delete_condition_where + " order by rowid",
    )
    hosts = res.fetchall()
    dirs_archived: dict[int, bool] = {}
    for host in hosts:
        host_info = HostInfo(
            id=host[0],
            hostname=host[1],
            long_hostname=host[2],
        )
        res2 = sql_execute(
            cur,
            "select rowid, name, modtime, deltime from directory "
            + 'where hostid = "'
            + str(host[0])
            + '"'
            + delete_condition_and
            + " order by rowid",
        )
        dirs = res2.fetchall()
        for dirrec in dirs:
            if dirrec[3] == 0 or args.show_deleted:
                # check if it's archive dir
                res3 = sql_execute(
                    cur,
                    f"select rowid, tarname, system from archive where dirid = {dirrec[0]} order by rowid",
                )
                archs = res3.fetchall()
                archive_entries: list[ArchiveEntry] = []
                for arch in archs:
                    archive_entries.append(ArchiveEntry(id=arch[0], tar_name=arch[1], system=arch[2]))
                has_archive = bool(archive_entries)
                dirs_archived[dirrec[0]] = has_archive
                host_info.directories.append(
                    DirectoryInfo(
                        id=dirrec[0],
                        name=dirrec[1],
                        mod_time=dirrec[2],
                        del_time=dirrec[3],
                        archives=archive_entries,
                        has_archive=has_archive,
                    )
                )
        info_datasets.hosts.append(host_info)

    #
    # Keys
    #
    res = sql_execute(cur, "select rowid, keyid from key order by rowid")
    keys = res.fetchall()
    for key in keys:
        info_datasets.keys.append(KeyInfo(id=key[0], key=key[1]))

    #
    # Time Series
    #
    res_ts = sql_execute(cur, "select tsid, name from timeseries order by tsid")
    for ts in res_ts:
        ts_id = int(ts[0])
        ts_info = TimeSeriesInfo(name=ts[1])
        info_datasets.time_series[ts_id] = ts_info

    #
    # Datasets
    #
    if not args.list_replicas and not args.list_files:
        res_ds = sql_execute(
            cur,
            "select rowid, uuid, name, modtime, deltime, fileformat, tsid from dataset "
            "where fileformat != 'VARIABLES'" + delete_condition_and + " order by rowid",
        )
        for dataset in res_ds:
            dataset_id = int(dataset[0])
            dataset_info = DatasetInfo(
                uuid=dataset[1],
                name=dataset[2],
                mod_time=dataset[3],
                del_time=dataset[4],
                file_format=dataset[5],
            )
            tsid = dataset[6]
            if tsid > 0:
                info_datasets.time_series[tsid].datasets[dataset_id] = dataset_info
            else:
                info_datasets.datasets[dataset_id] = dataset_info
    else:
        info_datas(args, info_datasets, cur, dirs_archived)
        info_texts(args, info_datasets, cur, dirs_archived)
        info_images(args, info_datasets, cur, dirs_archived)

    info_variables(info_datasets, cur)
    return info_datasets


def format_info_dataset_lines(  # pylint: disable=too-many-locals
    dataset_info: DatasetInfo,
) -> list[str]:
    lines = []
    time_str = timestamp_to_str(dataset_info.mod_time)
    dataset_line = f"    {dataset_info.uuid}   {dataset_info.file_format:6}  {time_str}   {dataset_info.name}"
    if dataset_info.del_time > 0:
        dataset_line += f"  - deleted {timestamp_to_str(dataset_info.del_time)}"
    lines.append(dataset_line)

    for replica_id, replica_info in dataset_info.replicas.items():
        flags = replica_info.flags
        flag_del = "D" if flags.deleted else "-"
        flag_encrypted = "k" if flags.encrypted else "-"
        flag_accuracy = "a" if flags.accuracy else "-"
        flag_archive = "A" if flags.archive else "-"
        flag_remote = "e" if flags.embedded else "r"
        replica_line = (
            f"  {replica_id:>7} {flag_remote}{flag_encrypted}{flag_accuracy}{flag_archive}{flag_del} "
            f"{replica_info.dir_id}"
        )
        if replica_info.archive_id > 0:
            replica_line += f".{replica_info.archive_id}"
        else:
            replica_line += "  "

        if dataset_info.file_format == "IMAGE" and replica_info.resolution is not None:
            res = replica_info.resolution
            resolution_text = f" {res.x} x {res.y}".rjust(14)
        else:
            resolution_text = " ".rjust(14)
        replica_line += f"{resolution_text}"

        replica_line += f" {sizeof_fmt(replica_info.size):>11}  {timestamp_to_str(replica_info.mod_time)}"
        replica_line += f"      {replica_info.name}"
        if flags.deleted:
            replica_line += f"  - deleted {timestamp_to_str(replica_info.del_time)}"
        lines.append(replica_line)

        for file_info in replica_info.files:
            if replica_info.key_id > 0:
                prefix = " " * 30 + f"k{replica_info.key_id:<3}"
            else:
                prefix = " " * 34
            file_line = prefix + f"{sizeof_fmt(file_info.len_compressed):>11}  {timestamp_to_str(file_info.mod_time)}"
            if file_info.checksum:
                file_line += f"         {file_info.checksum}  {file_info.name}"
            else:
                file_line += f"         {file_info.name}"
            lines.append(file_line)

    return lines


def format_info(info_data: InfoResult) -> str:  # pylint: disable=too-many-statements
    lines = []
    archive_info = info_data.archive
    created_time = timestamp_to_str(archive_info.mod_time)
    lines.append(f"{archive_info.name}, version {archive_info.version}, created on {created_time}")
    lines.append("")

    lines.append("Hosts and directories:")
    for host_info in info_data.hosts:
        lines.append(f"  {host_info.hostname}   longhostname = {host_info.long_hostname}")
        for dir_info in host_info.directories:
            archive_system = "  "
            if dir_info.archives:
                archive_system = f"  - Archive: {dir_info.archives[0].system}"
            lines.append(f"     {dir_info.id}. {dir_info.name}{archive_system}")
            for archive_entry in dir_info.archives:
                tar_name = archive_entry.tar_name if archive_entry.tar_name else "."
                lines.append(f"       {dir_info.id}.{archive_entry.id} {tar_name}")
    lines.append("")

    if info_data.keys:
        lines.append("Encryption keys:")
        for key_info in info_data.keys:
            lines.append(f"  k{key_info.id}. {key_info.key}")
        lines.append("")

    if info_data.time_series:
        lines.append("Time-series and their datasets:")
        for _ts_id, ts_info in info_data.time_series.items():
            lines.append(f"  {ts_info.name}")
            for _ds_id, dataset_info in sorted(ts_info.datasets.items()):
                lines.extend(format_info_dataset_lines(dataset_info))
        lines.append("")

    if info_data.datasets:
        lines.append("Other Datasets:")
        for _ds_id, dataset_info in sorted(info_data.datasets.items()):
            lines.extend(format_info_dataset_lines(dataset_info))
        lines.append("")

    if info_data.variables:
        lines.append("Variables:")
        for _variable_id, variable in sorted(info_data.variables.items()):
            primary = " primary" if variable.primary else ""
            lines.append(
                f"  {variable.run}/{variable.dataset}/{variable.variable}   definition={variable.definition}{primary}"
            )
            if variable.generated_by is not None:
                lines.append(f"      generated by: {variable.generated_by.uuid}")
            if variable.chunks:
                lines.append(f"      chunks: {len(variable.chunks)}")
            if variable.preferred_preview is not None:
                lines.append(
                    f"      preferred preview: {variable.preferred_preview.run}/"
                    f"{variable.preferred_preview.dataset}/"
                    f"{variable.preferred_preview.variable}"
                )
        lines.append("")

    if info_data.activities:
        lines.append("Activities:")
        for _activity_id, activity in sorted(info_data.activities.items()):
            lines.append(f"  {activity.uuid}   {activity.category}/{activity.action}")
            for activity_input in activity.inputs:
                lines.append(
                    f"      input[{activity_input.role}]: {activity_input.reference.run}/"
                    f"{activity_input.reference.dataset}/{activity_input.reference.variable}"
                )
            for output in activity.outputs:
                lines.append(
                    f"      output[{output.role}]: {output.reference.run}/"
                    f"{output.reference.dataset}/{output.reference.variable}"
                )
        lines.append("")

    return "\n".join(lines)


def print_info(info_data: InfoResult):
    output_text = format_info(info_data)
    if output_text:
        print(output_text)
