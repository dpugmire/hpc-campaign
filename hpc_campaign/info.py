@dataclass
class InfoResult:  # pylint: disable=too-many-instance-attributes
    """Aggregated archive information."""

    archive: ArchiveInfo
    hosts: list[HostInfo] = field(default_factory=list)
    keys: list[KeyInfo] = field(default_factory=list)
    time_series: dict[int, TimeSeriesInfo] = field(default_factory=dict)
    runs: dict[int, RunInfo] = field(default_factory=dict)
    variables: dict[int, LogicalVariableInfo] = field(default_factory=dict)
    activities: dict[int, ActivityInfo] = field(default_factory=dict)
    datasets: dict[int, DatasetInfo] = field(default_factory=dict)
    _variable_index: dict[VariableRef, int] = field(default_factory=dict, repr=False)
    _activity_index: dict[str, int] = field(default_factory=dict, repr=False)

    def find_variable(
        self,
        dataset: str,
        variable: str,
        run: str = DEFAULT_RUN,
    ) -> LogicalVariableInfo:
        """Find a logical variable by its public identity."""
        reference = VariableRef(run, dataset, variable)
        variable_id = self._variable_index.get(reference)
        if variable_id is not None:
            return self.variables[variable_id]
        for item in self.variables.values():
            if item.reference == reference:
                self._variable_index[reference] = item.id
                return item
        raise LookupError(f"Logical variable not found: {run}/{dataset}/{variable}")

    def find_activity(self, activity: ActivityRef | str) -> ActivityInfo:
        """Find an activity by its stable UUID."""
        activity_uuid = activity.uuid if isinstance(activity, ActivityRef) else str(activity)
        activity_id = self._activity_index.get(activity_uuid)
        if activity_id is not None:
            return self.activities[activity_id]
        for item in self.activities.values():
            if item.uuid == activity_uuid:
                self._activity_index[activity_uuid] = item.id
                return item
        raise LookupError(f"Activity not found: {activity_uuid}")

    def _variable_for_ref(self, reference: VariableRef) -> LogicalVariableInfo:
        return self.find_variable(reference.dataset, reference.variable, reference.run)

    def primary_variables(
        self,
        *,
        run: str | None = None,
        definition: str | None = None,
    ) -> list[LogicalVariableInfo]:
        """Return explicit primary bindings, optionally filtered by run or definition."""
        return [
            item
            for item in self.variables.values()
            if item.primary
            and (run is None or item.run == run)
            and (definition is None or item.definition == definition)
        ]

    def root_sources(self, reference: VariableRef) -> list[LogicalVariableInfo]:
        """Return all reachable variables that have no known derivation source."""
        roots: dict[int, LogicalVariableInfo] = {}
        visited: set[int] = set()

        def visit(item: LogicalVariableInfo) -> None:
            if item.id in visited:
                return
            visited.add(item.id)
            if item.generated_by is None:
                roots[item.id] = item
                return
            activity = self.find_activity(item.generated_by)
            for source in activity.inputs:
                visit(self.variables[source.variable_id])

        visit(self._variable_for_ref(reference))
        return [roots[key] for key in sorted(roots)]

    def derived_variables_from(
        self,
        reference: VariableRef,
        *,
        action: str | None = None,
        transitive: bool = True,
    ) -> list[LogicalVariableInfo]:
        """Return direct or transitive variables derived from a source."""
        start = self._variable_for_ref(reference)
        result: dict[int, LogicalVariableInfo] = {}
        pending = list(start.used_by)
        visited_activities: set[int] = set()
        while pending:
            activity_ref = pending.pop(0)
            activity_info = self.find_activity(activity_ref)
            if activity_info.id in visited_activities:
                continue
            visited_activities.add(activity_info.id)
            for output in activity_info.outputs:
                derived = self.variables[output.variable_id]
                if action is None or activity_info.action == action:
                    result[derived.id] = derived
                if transitive:
                    pending.extend(derived.used_by)
        return [result[key] for key in sorted(result)]

    def paths_to_root_sources(self, reference: VariableRef) -> list[list[VariableRef]]:
        """Return every direct-provenance path from a variable to a root source."""
        paths: list[list[VariableRef]] = []

        def visit(item: LogicalVariableInfo, path: list[VariableRef]) -> None:
            next_path = [*path, item.reference]
            if item.generated_by is None:
                paths.append(next_path)
                return
            activity = self.find_activity(item.generated_by)
            for source in activity.inputs:
                visit(self.variables[source.variable_id], next_path)

        visit(self._variable_for_ref(reference), [])
        return paths


